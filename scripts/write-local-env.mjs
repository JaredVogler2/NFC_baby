#!/usr/bin/env node
// Writes .env.local (git-ignored) for local development/tests from `supabase status`.
// The keys printed by the Supabase CLI for a LOCAL stack are well-known public demo keys, not
// secrets. Random per-machine values are generated for encryption/cron secrets.
import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const out = process.argv[2] ?? '.env.local'
const raw = execFileSync('npx', ['supabase', 'status', '-o', 'json'], { encoding: 'utf8' })
const status = JSON.parse(raw.slice(raw.indexOf('{')))

const previous = existsSync(out) ? readFileSync(out, 'utf8') : ''
const keep = (name, fallback) => previous.match(new RegExp(`^${name}=(.+)$`, 'm'))?.[1] ?? fallback

const port = process.env.E2E_PORT ?? '3000'
const lines = {
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  APP_URL: keep('APP_URL', `http://localhost:${port}`),
  BOOTSTRAP_OWNER_EMAIL: keep('BOOTSTRAP_OWNER_EMAIL', 'owner@example.test'),
  SMS_PROVIDER: keep('SMS_PROVIDER', 'off'),
  CONTACT_ENCRYPTION_KEY: keep('CONTACT_ENCRYPTION_KEY', randomBytes(32).toString('base64')),
  CRON_SECRET: keep('CRON_SECRET', randomBytes(32).toString('hex')),
  MAILPIT_URL: status.MAILPIT_URL ?? status.INBUCKET_URL,
  SUPABASE_DB_URL: status.DB_URL,
}
writeFileSync(
  out,
  `# Generated by scripts/write-local-env.mjs for the LOCAL Supabase stack. Do not commit.\n` +
    Object.entries(lines)
      .map(([k, v]) => `${k}=${v}`)
      .join('\n') +
    '\n',
)
console.log(`wrote ${out}`)
